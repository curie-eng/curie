// Codegen: generate the console's API wire types from apps/api/openapi.json
// with openapi-typescript, into the COMMITTED module src/api/generated.ts.
// client.ts aliases its API-backed types to `components["schemas"][...]`, so a
// changed response field reaches every consumer through `pnpm typecheck`.
//
// The output is committed (the UI Docker build has no apps/api in its context
// and must never run this). CI runs `pnpm gen:api-types --check`, which fails
// when openapi.json changed without a regeneration.
//
// Usage:
//   node scripts/gen-api-types.mjs [--schema <path>] [--output <path>] [--check]
//
// --check generates in memory and compares to the existing output without
// writing: exit 1 with "API types are stale" on a mismatch, "API types are
// missing" when the output does not exist, exit 0 when they are equal.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const uiRoot = join(here, "..");
const defaults = {
  schema: join(uiRoot, "..", "api", "openapi.json"),
  output: join(uiRoot, "src", "api", "generated.ts"),
};

function parseArgs(argv) {
  const opts = { ...defaults, check: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--check") {
      opts.check = true;
    } else if (arg === "--schema" || arg === "--output") {
      const value = argv[i + 1];
      if (!value || value.startsWith("--")) fail(`${arg} needs a path`);
      opts[arg.slice(2)] = resolve(value);
      i += 1;
    } else {
      fail(`unknown argument: ${arg}`);
    }
  }
  return opts;
}

function fail(message) {
  process.stderr.write(`gen-api-types: ${message}\n`);
  process.exit(1);
}

const banner = `// @generated by scripts/gen-api-types.mjs from apps/api/openapi.json
// Do not edit by hand. Regenerate with \`pnpm gen:api-types\` in apps/ui and commit.
`;

async function generate(schemaPath) {
  // defaultNonNullable: false keeps a defaulted field the API does not list as
  // required optional, so consumers must handle its absence honestly.
  // Parse the JSON ourselves and hand openapi-typescript the object, so the
  // output carries no absolute path and is identical on every machine.
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  const ast = await openapiTS(schema, { defaultNonNullable: false });
  return banner + "\n" + astToString(ast);
}

const opts = parseArgs(process.argv.slice(2));
const text = await generate(opts.schema);

if (opts.check) {
  if (!existsSync(opts.output)) {
    fail(`API types are missing: ${opts.output} does not exist; run 'pnpm gen:api-types' in apps/ui and commit.`);
  }
  if (readFileSync(opts.output, "utf8") !== text) {
    fail(`API types are stale: ${opts.output} does not match ${opts.schema}; run 'pnpm gen:api-types' in apps/ui and commit.`);
  }
  process.exit(0);
}

mkdirSync(dirname(opts.output), { recursive: true });
writeFileSync(opts.output, text);
