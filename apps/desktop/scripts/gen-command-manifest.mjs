// Codegen: turn the CLI's own `cli/command-manifest.json` (what `curie schema`
// prints) into the two forms this app consumes.
//
//   src/generated/commandManifest.ts    `as const`, for the renderer -- the
//     literal types are what make a renamed or removed command a typecheck
//     failure here instead of a runtime surprise.
//   src/generated/commandManifest.json  plain JSON, for the Electron main
//     process, which resolves invocations to argv and does not need the types.
//
// Both are committed, so a build with no `cli/` in its context still works.
// Run `pnpm gen:manifest` after changing the CLI surface and commit the result.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const source = join(root, "..", "..", "cli", "command-manifest.json");
const outDir = join(root, "src", "generated");

// Reparse so invalid JSON fails here, loudly, rather than at app start.
const manifest = JSON.parse(readFileSync(source, "utf8"));

mkdirSync(outDir, { recursive: true });

writeFileSync(
  join(outDir, "commandManifest.ts"),
  `// @generated by scripts/gen-command-manifest.mjs from cli/command-manifest.json
// Do not edit by hand. Run \`pnpm gen:manifest\` to refresh.
/* eslint-disable */
export const commandManifest = ${JSON.stringify(manifest, null, 2)} as const;
`,
);

writeFileSync(join(outDir, "commandManifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

const count = (function leaves(node) {
  const subs = node.subcommands ?? [];
  return subs.length ? subs.reduce((n, s) => n + leaves(s), 0) : 1;
})(manifest);
console.log(`command manifest: ${count} runnable commands`);
