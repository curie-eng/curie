// Codegen: the dispatcher's own Slack app manifest, as a string the renderer can
// show and the operator can copy.
//
// A copy typed into the desktop app would be a second source of truth for the
// scopes a Curie bot needs, and the first time somebody added one to
// `apps/dispatcher/slack-app-manifest.yaml` the app would start handing out a
// manifest that installs an app the dispatcher cannot use -- silently, because a
// missing scope fails at the Slack API call, hours later, not at install.
//
// So it is generated and committed, like the command manifest, and
// `slackManifest.test.ts` fails if the two drift.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const source = join(root, "..", "..", "apps", "dispatcher", "slack-app-manifest.yaml");
const outDir = join(root, "src", "generated");

const yaml = readFileSync(source, "utf8");

// The leading comment block is instructions to a human reading the file in the
// repo; the app states those itself, in its own words, beside the copy button.
// What gets copied should be exactly what Slack expects and nothing else.
const body = yaml.replace(/^(#[^\n]*\n)+/, "");

mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "slackManifest.ts"),
  `// GENERATED by scripts/gen-slack-manifest.mjs -- do not edit.\n` +
    `// Source: apps/dispatcher/slack-app-manifest.yaml\n\n` +
    `export const SLACK_APP_MANIFEST = ${JSON.stringify(body)};\n`,
);

const scopes = [...body.matchAll(/^\s+- ([a-z]+:[a-z.]+)$/gm)].map((m) => m[1]);
console.log(`slack manifest: ${body.split("\n").length} lines, ${scopes.length} bot scopes`);
