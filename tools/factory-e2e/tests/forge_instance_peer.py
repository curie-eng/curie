def serve(config_path: Path, state_dir: Path) -> None:
    peer = Peer(json.loads(config_path.read_text()), state_dir)

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, _format: str, *args: Any) -> None:
            pass

        def handle_request(self) -> None:
            length = int(self.headers.get("Content-Length", "0"))
            raw = self.rfile.read(length) if length else b"{}"
            try:
                body = json.loads(raw)
            except ValueError:
                body = {}
            status, payload = peer.respond(self.command, self.path, self.headers, body)
            encoded = json.dumps(payload).encode()
            self.send_response(status)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(encoded)))
            self.send_header("X-Next-Page", "")
            self.end_headers()
            self.wfile.write(encoded)

        do_GET = handle_request
        do_POST = handle_request
        do_PUT = handle_request
        do_DELETE = handle_request

    server = ThreadingHTTPServer(("0.0.0.0", peer.config["port"]), Handler)
    if peer.config.get("tls"):
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.minimum_version = ssl.TLSVersion.TLSv1_2
        context.load_cert_chain(peer.config["certificate"], peer.config["private_key"])
        server.socket = context.wrap_socket(server.socket, server_side=True)
    server.serve_forever()


def bridge(listen: int, host: str, port: int) -> None:
    class Forward(socketserver.BaseRequestHandler):
        def handle(self) -> None:
            with socket.create_connection((host, port), timeout=10) as upstream:
                upstream.settimeout(None)
                while True:
                    readable, _, _ = select.select((self.request, upstream), (), (), 60)
                    for source in readable:
                        data = source.recv(65536)
                        if not data:
                            return
                        (upstream if source is self.request else self.request).sendall(data)

    class Server(socketserver.ThreadingTCPServer):
        allow_reuse_address = True
        daemon_threads = True

    with Server(("127.0.0.1", listen), Forward) as server:
        server.serve_forever()


