STATE_LABELS = [
    "curie-factory",
    "curie-factory:queued",
    "curie-factory:running",
    "curie-factory:pr-open",
    "curie-factory:needs-human",
]
# Below the CLI's 15 s HTTP timeout, so a held label POST never fails it.
LABEL_HOLD_SECONDS = 12


class Peer:
    def __init__(self, config: dict[str, Any], state_dir: Path) -> None:
        self.config = config
        self.lock = threading.RLock()
        self.release = threading.Event()
        self.release.set()
        state_dir.mkdir(parents=True, exist_ok=True)
        self.db = sqlite3.connect(state_dir / "peer.sqlite3", check_same_thread=False)
        self.db.executescript(
            "CREATE TABLE IF NOT EXISTS requests (seq INTEGER PRIMARY KEY, "
            "method TEXT, path TEXT, "
            "credential INTEGER, operation TEXT);"
            "CREATE TABLE IF NOT EXISTS labels (project TEXT, name TEXT, "
            "PRIMARY KEY(project,name));"
            "CREATE TABLE IF NOT EXISTS controls (name TEXT PRIMARY KEY, value TEXT);"
        )
        for project in config.get("projects", []):
            for label in STATE_LABELS:
                self.db.execute(
                    "INSERT OR IGNORE INTO labels VALUES (?,?)", (str(project["id"]), label)
                )
        self.db.commit()

    def credential(self, headers: Any) -> int:
        value = headers.get("PRIVATE-TOKEN", "")
        if self.config["kind"] == "jira":
            raw = headers.get("Authorization", "")
            try:
                pair = base64.b64decode(raw.removeprefix("Basic "), validate=True).decode()
            except (ValueError, UnicodeError):
                return -1
            username, _, value = pair.partition(":")
            if username not in self.config["usernames"]:
                return -1
        elif self.config["kind"] in ("github", "dc"):
            authorization = headers.get("Authorization", "")
            value = authorization.removeprefix("Bearer ")
            if self.config["kind"] == "github" and authorization.startswith("Basic "):
                try:
                    pair = base64.b64decode(authorization[6:], validate=True).decode()
                    username, _, value = pair.partition(":")
                    if username != "x-access-token":
                        return -1
                except (ValueError, UnicodeError):
                    return -1
            # App JWTs are generated by the real CLI from the fixture's private key.
            if self.config["kind"] == "github" and value.count(".") == 2:
                return 100
        try:
            return self.config["tokens"].index(value)
        except ValueError:
            return -1

    def record(self, method: str, path: str, credential: int, operation: str) -> None:
        with self.lock:
            self.db.execute(
                "INSERT INTO requests (method,path,credential,operation) VALUES (?,?,?,?)",
                (method, path, credential, operation),
            )
            self.db.commit()

    def control(self, path: str, body: dict[str, Any]) -> Any:
        with self.lock:
            if path == "/__fixture/receipts":
                return {
                    "requests": [
                        dict(
                            zip(
                                ("seq", "method", "path", "credential", "operation"),
                                row,
                                strict=True,
                            )
                        )
                        for row in self.db.execute("SELECT * FROM requests ORDER BY seq")
                    ],
                    "label_writes": self.db.execute(
                        "SELECT count(*) FROM requests WHERE operation='label_write'"
                    ).fetchone()[0],
                    "labels": list(self.db.execute("SELECT * FROM labels ORDER BY project,name")),
                    "barrier_entered": self.db.execute(
                        "SELECT value FROM controls WHERE name='entered'"
                    ).fetchone()
                    == ("yes",),
                }
            if path == "/__fixture/arm":
                self.release.clear()
                self.db.executemany(
                    "DELETE FROM labels WHERE name=?", [(name,) for name in body["labels"]]
                )
                self.db.execute(
                    "INSERT OR REPLACE INTO controls VALUES ('barrier',?)",
                    (json.dumps(body["labels"]),),
                )
                self.db.execute("DELETE FROM controls WHERE name='entered'")
            elif path == "/__fixture/release":
                self.release.set()
                self.db.execute("DELETE FROM controls WHERE name='barrier'")
            elif path == "/__fixture/identity":
                self.db.execute("INSERT OR REPLACE INTO controls VALUES ('bot',?)", (body["bot"],))
            elif path == "/__fixture/restore":
                self.release.set()
                self.db.execute("DELETE FROM controls")
                self.db.execute("DELETE FROM labels")
                self.db.executemany("INSERT INTO labels VALUES (?,?)", body["labels"])
                # Request logs are observations, not operator-prepared state.
            else:
                return {"error": "unknown fixture control"}
            self.db.commit()
            return {"ok": True}

    def respond(
        self, method: str, raw_path: str, headers: Any, body: dict[str, Any]
    ) -> tuple[int, Any]:
        path = urlsplit(raw_path).path
        query = parse_qs(urlsplit(raw_path).query)
        if path == "/__fixture/health":
            return 200, {"ok": True}
        if path.startswith("/__fixture/"):
            if headers.get("X-Fixture-Control") != self.config["control"]:
                return 403, {"error": "fixture control authentication"}
            return 200, self.control(path, body)
        credential = self.credential(headers)
        anonymous = (
            path == "/_edge/tenant_info"
            or path == "/meta"
            or self.config["kind"] == "github"
            and path.startswith("/users/")
        )
        operation = "read"
        if path.endswith("/issues") and method == "GET":
            operation = "poll"
        elif path.endswith("/search/jql"):
            operation = "poll"
        elif "/issues/" in path or "/issue/" in path:
            operation = "ticket"
        elif path.endswith("/labels") and method == "POST":
            operation = "label_write"
        self.record(method, raw_path, credential, operation)
        if credential < 0 and not anonymous:
            return 401, {"message": "fixture credential refused"}
        match self.config["kind"]:
            case "gitlab":
                return self.gitlab(method, path, body)
            case "jira":
                return self.jira(method, path, query)
            case "github":
                return self.github(method, path, credential)
            case "dc":
                return self.dc(path)
        return 404, {"message": "unknown provider"}

    def gitlab(self, method: str, path: str, body: dict[str, Any]) -> tuple[int, Any]:
        # Alternate context paths deliberately reach the same external instance.
        # The CLI must refuse the recorded identity conflict rather than relying
        # on a provider 404 to protect the release.
        _, found, path = path.partition("/api/v4")
        if not found:
            return 404, {"message": "not an API path"}
        if path == "/version":
            return 200, {"version": "18.4.1", "revision": "fixture"}
        if path == "/personal_access_tokens/self":
            return 200, {
                "id": 11,
                "name": "fixture",
                "user_id": 9,
                "active": True,
                "revoked": False,
                "scopes": ["api", "write_repository"],
                "expires_at": None,
            }
        if path == "/user" or path == "/users/9":
            return 200, {"id": 9, "username": "acme-factory-bot", "state": "active", "bot": True}
        if not path.startswith("/projects/"):
            return 404, {"message": "not found"}
        parts = path.removeprefix("/projects/").split("/")
        key = unquote(parts[0])
        project = next(
            (p for p in self.config["projects"] if key in (str(p["id"]), p["path"])), None
        )
        if project is None:
            return 404, {"message": "project not found"}
        pid = str(project["id"])
        tail = "/".join(parts[1:])
        if not tail:
            return 200, {
                "id": project["id"],
                "path_with_namespace": project["path"],
                "default_branch": "main",
                "issues_enabled": True,
                "issues_access_level": "enabled",
                "visibility": "private",
                "http_url_to_repo": self.config["origin"] + "/" + project["path"] + ".git",
            }
        if tail == "members/all/9":
            return 200, {"id": 9, "username": "acme-factory-bot", "access_level": 40}
        if tail == "labels":
            if method == "POST":
                with self.lock:
                    barrier = self.db.execute(
                        "SELECT value FROM controls WHERE name='barrier'"
                    ).fetchone()
                    paused = barrier is not None and body.get("name") in json.loads(barrier[0])
                    if paused:
                        self.db.execute("INSERT OR REPLACE INTO controls VALUES ('entered','yes')")
                        self.db.commit()
                # Each held POST answers within the CLI's 15 s HTTP timeout, so
                # the barrier's window is the sum of the holds over its labels.
                if paused:
                    self.release.wait(LABEL_HOLD_SECONDS)
                with self.lock:
                    self.db.execute(
                        "INSERT OR IGNORE INTO labels VALUES (?,?)", (pid, body["name"])
                    )
                    self.db.commit()
                return 201, {"id": 20, **body}
            with self.lock:
                names = list(self.db.execute("SELECT name FROM labels WHERE project=?", (pid,)))
            return 200, [
                {"id": i + 1, "name": r[0], "color": "#6699cc"} for i, r in enumerate(names)
            ]
        if tail in ("issues", "issues/1/notes", "events"):
            return 200, []
        if tail == "issues/1":
            return 200, {
                "id": 101,
                "iid": 1,
                "project_id": project["id"],
                "title": self.config["content"],
                "description": self.config["content"],
                "state": "opened",
                "labels": [],
                "author": {"id": 12, "username": "acme-user"},
                "created_at": "2026-01-01T00:00:00Z",
                "updated_at": "2026-01-01T00:00:00Z",
            }
        if tail.startswith("repository/branches/"):
            return 200, {"name": "main", "commit": {"id": "1" * 40}, "protected": False}
        return 404, {"message": "not found"}

